/// Generates `lib/src/pricing_targets.dart` — the checked-in, reviewed
/// pricing source for BOTH stores (see that file's header). Values come from
/// Google's `pricing:convertRegionPrices` table (FX-current, tax-aware,
/// market-rounded), with anchor currencies (USD/EUR/GBP) at the USD nominal
/// and per-territory resolution where a currency's regions disagree (CHF:
/// CH vs LI). CNY has no Google reference (no Play in China) and keeps
/// Apple's mainland-China market pricing.
///
/// Re-run quarterly (or after big FX moves) alongside `audit_prices.dart`,
/// review the git diff of the generated file, then re-run asc-products +
/// play-products to apply.
///
/// Run: source ~/.localrc && dart run bin/generate_pricing_targets.dart
import 'dart:convert';
import 'dart:io';

import 'package:googleapis_auth/auth_io.dart';
import 'package:provisioning/src/api_client.dart';

void main() async {
  final env = Platform.environment;
  final sa = ServiceAccountCredentials.fromJson(
    jsonDecode(
      await File(
        env['OBS_BLADE_GOOGLE_APPLICATION_CREDENTIALS']!,
      ).readAsString(),
    ),
  );
  final authClient = await clientViaServiceAccount(sa, [
    'https://www.googleapis.com/auth/androidpublisher',
  ]);
  final play = HttpApiClient(
    baseUrl: 'https://androidpublisher.googleapis.com',
    client: authClient,
  );
  const pkg = 'com.kounex.obsBlade';

  String money(Map p) {
    final nanos = (p['nanos'] as num?) ?? 0;
    return '${p['units']}'
        '${nanos > 0 ? '.${(nanos ~/ 10000000).toString().padLeft(2, '0')}' : ''}';
  }

  Future<(Map<String, Map<String, String>>, String)> table(
    String usdPrice,
  ) async {
    final parts = usdPrice.split('.');
    final res = await play.post(
      'androidpublisher/v3/applications/$pkg/pricing:convertRegionPrices',
      {
        'price': {
          'currencyCode': 'USD',
          'units': parts[0],
          'nanos': int.parse('${parts[1]}0000000'),
        },
      },
    );
    final converted =
        (res.json['convertedRegionPrices'] as Map<String, Object?>?) ?? {};
    final version =
        ((res.json['regionVersion'] as Map?)?['version'] as String?) ?? '?';
    final out = <String, Map<String, String>>{};
    for (final entry in converted.entries) {
      final p = (entry.value as Map?)?['price'] as Map<String, Object?>?;
      if (p == null) continue;
      out[entry.key] = {
        'currency': p['currencyCode'] as String,
        'price': money(p),
      };
    }
    return (out, version);
  }

  final (monthly, monthlyVersion) = await table('4.99');
  final (yearly, _) = await table('49.99');
  final (lifetime, _) = await table('99.99');
  authClient.close();

  // Play region → currency (identical across the three tables).
  final regionCurrency = {
    for (final e in monthly.entries) e.key: e.value['currency']!,
  };

  // currency → set of regions using it.
  final currencyRegions = <String, List<String>>{};
  for (final e in regionCurrency.entries) {
    currencyRegions.putIfAbsent(e.value, () => []).add(e.key);
  }

  const anchors = {'USD', 'EUR', 'GBP'};
  // Mainland China: no Google reference (Play doesn't operate there) — keep
  // Apple's CNY market pricing (verified live 2026-10: $3.87/$33.06/$103.96).
  const cnyKeep = ('26', '222', '698');

  final conflicts = <String>[];
  final byCurrency = <String, (String, String, String)>{};
  final byRegion = <String, (String, String, String)>{};
  final currencies = currencyRegions.keys.toList()..sort();
  for (final currency in currencies) {
    if (anchors.contains(currency)) continue;
    final regions = currencyRegions[currency]!;
    final m = regions.map((r) => monthly[r]!['price']!).toSet();
    final y = regions.map((r) => yearly[r]!['price']!).toSet();
    final l = regions.map((r) => lifetime[r]!['price']!).toSet();
    if (m.length == 1 && y.length == 1 && l.length == 1) {
      byCurrency[currency] = (m.single, y.single, l.single);
    } else if (currency == 'CHF') {
      // CH and LI price differently — resolve per region (ASC territory
      // ids CHE/LIE map 1:1 to the Play region codes).
      for (final r in regions) {
        byRegion[r] = (
          monthly[r]!['price']!,
          yearly[r]!['price']!,
          lifetime[r]!['price']!,
        );
      }
    } else {
      conflicts.add(
        '$currency (${regions.join(',')}): '
        'monthly ${m.join('/')}, yearly ${y.join('/')}, lifetime ${l.join('/')}',
      );
    }
  }
  if (conflicts.isNotEmpty) {
    stderr.writeln(
      'Unresolved currency conflicts — extend the generator policy for '
      'these before committing a table:\n  ${conflicts.join('\n  ')}',
    );
    exitCode = 1;
    return;
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by bin/generate_pricing_targets.dart — do not')
    ..writeln('// hand-edit. Re-run the generator and review the diff.')
    ..writeln('//')
    ..writeln(
      '// The reviewed pricing source for BOTH stores: anchor currencies',
    )
    ..writeln('// (USD/EUR/GBP) at the USD nominal, every other currency at')
    ..writeln("// Google's convertRegionPrices table (regionVersion")
    ..writeln('// $monthlyVersion — FX-current, tax-aware, market-rounded).')
    ..writeln('// asc-products snaps each value to the nearest App Store price')
    ..writeln('// point; play-products writes the exact value per region.')
    ..writeln('//')
    ..writeln('// Policy decisions baked in:')
    ..writeln('// - CNY: no Google reference (no Play in China) — keeps')
    ..writeln('//   Apple\'s mainland-China market pricing.')
    ..writeln('// - CHF: CH and LI price differently on Google — per-territory')
    ..writeln('//   rows below (CHE/LIE on ASC, CH/LI on Play).')
    ..writeln('// - iOS lifetime (pro_lifetime) is NOT driven by this table:')
    ..writeln('//   its auto-equalized price schedule is FX-current and')
    ..writeln('//   Apple maintains it (verified 2026-10).')
    ..writeln('/// Reviewed pricing targets — see the header above.')
    ..writeln('class PricingTargets {')
    ..writeln('  PricingTargets._();')
    ..writeln()
    ..writeln("  static const monthlyUsd = '4.99';")
    ..writeln("  static const yearlyUsd = '49.99';")
    ..writeln("  static const lifetimeUsd = '99.99';")
    ..writeln()
    ..writeln('  /// The Google convertRegionPrices table version these values')
    ..writeln('  /// came from — Play writes must pass a current regionVersion')
    ..writeln('  /// (an older one is rejected for regions whose currency')
    ..writeln('  /// changed since).')
    ..writeln("  static const googleTableVersion = '$monthlyVersion';")
    ..writeln()
    ..writeln('  /// Currencies kept at the USD nominal (4.99/49.99/99.99).')
    ..writeln("  static const anchorCurrencies = {'USD', 'EUR', 'GBP'};")
    ..writeln()
    ..writeln('  /// (monthly, yearly, lifetime) per non-anchor currency.')
    ..writeln(
      '  static const byCurrency = <String, (String, String, String)>{',
    );
  for (final e in byCurrency.entries) {
    buffer.writeln(
      "    '${e.key}': ('${e.value.$1}', '${e.value.$2}', '${e.value.$3}'),",
    );
  }
  buffer
    ..writeln(
      "    // No Google reference — Apple's mainland-China market pricing.",
    )
    ..writeln("    'CNY': ('${cnyKeep.$1}', '${cnyKeep.$2}', '${cnyKeep.$3}'),")
    ..writeln('  };')
    ..writeln()
    ..writeln('  /// Per-region rows where a currency\'s regions disagree.')
    ..writeln('  /// Keys are Play region codes; the identical ISO-3 codes')
    ..writeln('  /// (CHE/LIE) address the ASC territories.')
    ..writeln('  static const byRegion = <String, (String, String, String)>{');
  for (final e in byRegion.entries) {
    buffer.writeln(
      "    '${e.key}': ('${e.value.$1}', '${e.value.$2}', '${e.value.$3}'),",
    );
  }
  buffer
    ..writeln('  };')
    ..writeln()
    ..writeln('  /// Play region → currency (from the Google table).')
    ..writeln('  static const playRegionCurrency = <String, String>{');
  for (final e
      in (regionCurrency.entries.toList()
        ..sort((a, b) => a.key.compareTo(b.key)))) {
    buffer.writeln("    '${e.key}': '${e.value}',");
  }
  buffer
    ..writeln('  };')
    ..writeln()
    ..writeln('  /// The target price string for [currency] and a product')
    ..writeln('  /// identified by its USD nominal, honouring per-territory')
    ..writeln('  /// overrides. Null when neither covers it.')
    ..writeln(
      '  static String? target(String currency, String priceUsd, {String? region}) {',
    )
    ..writeln('    final row =')
    ..writeln('        (region != null ? byRegion[region] : null) ??')
    ..writeln('        byCurrency[currency];')
    ..writeln('    if (row == null) {')
    ..writeln('      if (!anchorCurrencies.contains(currency)) return null;')
    ..writeln('      return switch (priceUsd) {')
    ..writeln('        monthlyUsd => monthlyUsd,')
    ..writeln('        yearlyUsd => yearlyUsd,')
    ..writeln('        lifetimeUsd => lifetimeUsd,')
    ..writeln('        _ => null,')
    ..writeln('      };')
    ..writeln('    }')
    ..writeln('    return switch (priceUsd) {')
    ..writeln('      monthlyUsd => row.\$1,')
    ..writeln('      yearlyUsd => row.\$2,')
    ..writeln('      lifetimeUsd => row.\$3,')
    ..writeln('      _ => null,')
    ..writeln('    };')
    ..writeln('  }')
    ..writeln('}');

  final outFile = File('lib/src/pricing_targets.dart');
  await outFile.writeAsString(buffer.toString());
  print(
    'wrote ${outFile.path}: ${byCurrency.length + 1} currencies '
    '(+3 anchors, +CNY), ${byRegion.length} region overrides, '
    '${regionCurrency.length} Play regions, Google table $monthlyVersion',
  );
}
